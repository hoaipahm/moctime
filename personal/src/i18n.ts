export type CopyKey = keyof typeof copy;
export function t(locale: Locale, key: CopyKey): string {
  return copy[key][locales.indexOf(locale)];
}
export function dateFormat(
  locale: Locale,
  date: Date | string,
  options: Intl.DateTimeFormatOptions = {},
): string {
  return new Intl.DateTimeFormat(intlLocales[locale], options).format(
    typeof date === "string"
      ? new Date(date + (date.length === 10 ? "T12:00:00" : ""))
      : date,
  );
}
